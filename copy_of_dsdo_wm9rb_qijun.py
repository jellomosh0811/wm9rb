print("Supplementary Regression Analysis")

from sklearn.ensemble import RandomForestRegressor
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import train_test_split, GridSearchCV
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

reg_data = df_model.dropna(subset=['Rating']).copy()

X_reg = reg_data[features].copy()
y_reg = reg_data['Rating'].copy()

X_reg = X_reg.replace([np.inf, -np.inf], np.nan)

X_train_reg, X_test_reg, y_train_reg, y_test_reg = train_test_split(
    X_reg,
    y_reg,
    test_size=0.2,
    random_state=42
)

numeric_cols_reg = X_train_reg.select_dtypes(include=['int64', 'float64']).columns
categorical_cols_reg = X_train_reg.select_dtypes(include=['object', 'category']).columns

for col in numeric_cols_reg:
    median_val = X_train_reg[col].median()
    X_train_reg.loc[:, col] = X_train_reg[col].fillna(median_val)
    X_test_reg.loc[:, col] = X_test_reg[col].fillna(median_val)

for col in categorical_cols_reg:
    mode_val = X_train_reg[col].mode()[0] if not X_train_reg[col].mode().empty else 'Unknown'
    X_train_reg.loc[:, col] = X_train_reg[col].fillna(mode_val)
    X_test_reg.loc[:, col] = X_test_reg[col].fillna(mode_val)

X_train_reg = pd.get_dummies(X_train_reg, drop_first=True)
X_test_reg = pd.get_dummies(X_test_reg, drop_first=True)
X_train_reg, X_test_reg = X_train_reg.align(X_test_reg, join='left', axis=1, fill_value=0)

param_grid_reg = {
    'n_estimators': [100, 200],
    'max_depth': [None, 10, 20],
    'min_samples_split': [2, 5],
    'min_samples_leaf': [1, 2],
    'max_features': ['sqrt', 'log2']
}

grid_rf_reg = GridSearchCV(
    estimator=RandomForestRegressor(random_state=42),
    param_grid=param_grid_reg,
    cv=5,
    scoring='neg_root_mean_squared_error',
    n_jobs=-1
)

grid_rf_reg.fit(X_train_reg, y_train_reg)

best_rf_reg = grid_rf_reg.best_estimator_
y_pred_reg = best_rf_reg.predict(X_test_reg)

mae = mean_absolute_error(y_test_reg, y_pred_reg)
rmse = np.sqrt(mean_squared_error(y_test_reg, y_pred_reg))
r2 = r2_score(y_test_reg, y_pred_reg)

reg_summary = pd.DataFrame({
    'Metric': ['MAE', 'RMSE', 'R2'],
    'Score': [mae, rmse, r2]
}).round(4)

best_params_reg = pd.DataFrame(
    list(grid_rf_reg.best_params_.items()),
    columns=['Parameter', 'Best Value']
)

