"""# 3. Feature Engineering"""

print("Feature Engineering")

import numpy as np
import pandas as pd

df_clean['Is_Paid'] = df_clean['Type'].apply(lambda x: 1 if x == 'Paid' else 0)
def price_category(price):
    if pd.isna(price):
        return 'Unknown'
    elif price == 0:
        return 'Free'
    elif price < 5:
        return 'Low'
    else:
        return 'High'
df_clean['Price_Category'] = df_clean['Price_num'].apply(price_category)
def install_level(installs):
    if pd.isna(installs):
        return 'Unknown'
    elif installs < 10000:
        return 'Low'
    elif installs < 1000000:
        return 'Medium'
    else:
        return 'High'
df_clean['Install_Level'] = df_clean['Installs_num'].apply(install_level)
df_clean['Review_Ratio'] = df_clean['Reviews'] / df_clean['Installs_num']
df_clean['Review_Ratio'] = df_clean['Review_Ratio'].replace([np.inf, -np.inf], np.nan)
df_clean['Review_Ratio'] = df_clean['Review_Ratio'].fillna(0)
df_clean['Log_Installs'] = np.log1p(df_clean['Installs_num'])
df_clean['Log_Price'] = np.log1p(df_clean['Price_num'].fillna(0))
def normalize_size(val):
    if pd.isna(val):
        return np.nan
    val_str = str(val).strip().upper()
    if val_str == '' or 'VARIES' in val_str:
        return np.nan
    try:
        if val_str.endswith('M'):
            return float(val_str[:-1]) * 1024
        elif val_str.endswith('K'):
            return float(val_str[:-1])
        else:
            return np.nan
    except:
        return np.nan
df_clean['Size_KB'] = df_clean['Size'].apply(normalize_size)
def size_category(size_kb):
    if pd.isna(size_kb):
        return 'Unknown'
    elif size_kb < 10000:
        return 'Small'
    elif size_kb < 30000:
        return 'Medium'
    else:
        return 'Large'
df_clean['Size_Category'] = df_clean['Size_KB'].apply(size_category)
df_clean['Rating_Class'] = df_clean['Rating'].apply(
    lambda x: 'High' if pd.notna(x) and x >= 4 else ('Low' if pd.notna(x) else np.nan)
)

